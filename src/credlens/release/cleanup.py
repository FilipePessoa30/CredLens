"""Gate B - tracked-but-ephemeral index cleanup (Fase 11B section 11).

Fase 11A's release inventory found 1,024 tracked files that are real,
accidentally-committed BYPRODUCTS of running tests/monitoring/coverage
locally - never release content:

- `reports/modeling/quarantine/*.manifest.json` (721 files) - one per
  local `credlens model`/test run that quarantined input rows.
- `reports/monitoring/alerts/*.json` (164 files) - one per local
  monitoring run that raised at least one alert.
- `reports/monitoring/runs/RUN_*/run.json` (138 files) - one per local
  monitoring run invocation. Deliberately EXCLUDES `reports/monitoring/
  runs/BATCHSET_REF_MODEL_behavioral_default_v1/batch_manifest.json`,
  a genuine, load-bearing reference fixture `run_monitoring()`/
  `run_detection_evaluation()` read as an INPUT - not ephemeral output,
  and must stay tracked (see `_RUNS_REFERENCE_PREFIX`).
- `coverage.json` (1 file) - regenerated by every `pytest --cov-
  report=json` invocation.

This module only READS the index (`git ls-files`, `git ls-files -s`,
`git cat-file`) to build a manifest of what's there and why it's
ephemeral - it never removes anything itself. Actual removal
(`git rm --cached`, never a physical delete) is a separate, explicit
step (`execute_cleanup`) gated on an already-written, human-reviewable
manifest, exactly as Fase 11B section 11.4 requires.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any

CLEANUP_MANIFEST_PATH = Path("reports/release/tracked_cleanup_manifest.json")
CLEANUP_MANIFEST_SCHEMA_VERSION = 1

# Windows CreateProcess has a real command-line length ceiling (see
# `credlens.release.staging`'s identical constant) - every batch git
# subprocess call in this module respects it.
_BATCH_SIZE = 200

# The one path under `reports/monitoring/runs/` that must NEVER be
# proposed for removal - see module docstring.
_RUNS_REFERENCE_PREFIX = "reports/monitoring/runs/BATCHSET_"


class CleanupManifestError(Exception):
    """Raised when the cleanup manifest cannot be built, or when the
    actually-tracked ephemeral paths no longer match an already-written
    manifest (a hard stop, per section 11.4 - never remove more, less,
    or different paths than were reviewed)."""


@dataclass(frozen=True)
class CleanupGroup:
    group_id: str
    git_prefix: str
    classification: str
    reason: str
    reproducible: bool
    reproducible_note: str
    gitignore_rule: str
    paths: tuple[str, ...]
    total_size_bytes: int
    aggregate_hash: str

    @property
    def quantity(self) -> int:
        return len(self.paths)

    def planned_command(self) -> str:
        """A description of the command `execute_cleanup` actually runs -
        NEVER a bare `git rm -r --cached -- {git_prefix}`, even when
        every current file under the prefix is ephemeral: that form
        would silently also remove any FUTURE non-ephemeral file added
        under the same prefix (exactly the mistake this group's own
        carve-out - e.g. `monitoring_runs` excluding `BATCHSET_*/` -
        exists to prevent). The real removal always targets this
        group's exact, individually-enumerated `paths`, batched."""
        if len(self.paths) == 1:
            return f"git rm --cached -- {self.paths[0]}"
        return f"git rm --cached -- <{self.quantity} explicit path(s) under {self.gitignore_rule}>"

    def to_dict(self) -> dict[str, Any]:
        return {
            "group_id": self.group_id,
            "path": self.git_prefix,
            "classification": self.classification,
            "quantity": self.quantity,
            "size_bytes": self.total_size_bytes,
            "hash": self.aggregate_hash,
            "reason": self.reason,
            "reproducible": self.reproducible,
            "reproducible_note": self.reproducible_note,
            "stays_on_disk": True,
            "gitignore_rule": self.gitignore_rule,
            "planned_command": self.planned_command(),
            "sample_paths": list(self.paths[:5]),
        }


@dataclass(frozen=True)
class CleanupManifest:
    schema_version: int
    groups: tuple[CleanupGroup, ...]

    @property
    def total_quantity(self) -> int:
        return sum(g.quantity for g in self.groups)

    @property
    def total_size_bytes(self) -> int:
        return sum(g.total_size_bytes for g in self.groups)

    @property
    def all_paths(self) -> tuple[str, ...]:
        return tuple(p for g in self.groups for p in g.paths)

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "n_groups": len(self.groups),
            "total_quantity": self.total_quantity,
            "total_size_bytes": self.total_size_bytes,
            "groups": [g.to_dict() for g in self.groups],
        }


def _batched(seq: list[str], size: int = _BATCH_SIZE) -> list[list[str]]:
    return [seq[i : i + size] for i in range(0, len(seq), size)]


def _tracked(repo_root: Path, prefix: str) -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", prefix], cwd=repo_root, capture_output=True, text=True, check=True
    )
    return sorted(line for line in result.stdout.splitlines() if line)


def _blob_ids(repo_root: Path, paths: list[str]) -> dict[str, str]:
    ids: dict[str, str] = {}
    for batch in _batched(paths):
        if not batch:
            continue
        result = subprocess.run(
            ["git", "ls-files", "-s", "--", *batch],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=True,
        )
        for line in result.stdout.splitlines():
            meta, _tab, path = line.partition("\t")
            ids[path] = meta.split()[1]
    return ids


def _total_blob_size(repo_root: Path, blob_ids: list[str]) -> int:
    total = 0
    for batch in _batched(blob_ids):
        if not batch:
            continue
        result = subprocess.run(
            ["git", "cat-file", "--batch-check=%(objectsize)"],
            cwd=repo_root,
            input="\n".join(batch),
            capture_output=True,
            text=True,
            check=True,
        )
        total += sum(int(line) for line in result.stdout.split())
    return total


def _aggregate_hash(blob_ids: list[str]) -> str:
    return hashlib.sha256("\n".join(sorted(blob_ids)).encode("utf-8")).hexdigest()


# One entry per Fase 11B section 11.1 minimum-evaluated path. Only paths
# with concrete evidence (Fase 11A's inventory run) are listed here -
# "não inclua outros caminhos sem evidência" (section 11.1).

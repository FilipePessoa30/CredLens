def _group_paths(repo_root: Path, group_id: str, git_prefix: str) -> list[str]:
    tracked = _tracked(repo_root, git_prefix)
    if group_id == "monitoring_runs":
        return [p for p in tracked if not p.startswith(_RUNS_REFERENCE_PREFIX)]
    return tracked


def build_cleanup_manifest(repo_root: Path | None = None) -> CleanupManifest:
    repo_root = repo_root or Path.cwd()
    groups = []
    for (
        group_id,
        git_prefix,
        classification,
        reason,
        reproducible,
        reproducible_note,
        gitignore_rule,
    ) in _GROUP_DEFINITIONS:
        paths = _group_paths(repo_root, group_id, git_prefix)
        blob_id_map = _blob_ids(repo_root, paths)
        blob_ids = [blob_id_map[p] for p in paths]
        groups.append(
            CleanupGroup(
                group_id=group_id,
                git_prefix=git_prefix,
                classification=classification,
                reason=reason,
                reproducible=reproducible,
                reproducible_note=reproducible_note,
                gitignore_rule=gitignore_rule,
                paths=tuple(paths),
                total_size_bytes=_total_blob_size(repo_root, blob_ids),
                aggregate_hash=_aggregate_hash(blob_ids),
            )
        )
    return CleanupManifest(schema_version=CLEANUP_MANIFEST_SCHEMA_VERSION, groups=tuple(groups))


def write_cleanup_manifest(manifest: CleanupManifest, repo_root: Path | None = None) -> Path:
    repo_root = repo_root or Path.cwd()
    out_path = repo_root / CLEANUP_MANIFEST_PATH
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(manifest.to_dict(), indent=2) + "\n", encoding="utf-8")
    return out_path


@dataclass(frozen=True)
class CleanupExecutionResult:
    dry_run: bool
    removed_paths: tuple[str, ...]
    index_diff_matches_plan: bool


def execute_cleanup(
    manifest: CleanupManifest, repo_root: Path | None = None, *, dry_run: bool = True
) -> CleanupExecutionResult:
    """Removes exactly `manifest.all_paths` from the git INDEX only
    (`git rm --cached`, never bare `git rm`) - the files stay on disk
    untouched. Refuses (raises `CleanupManifestError`) if the currently
    tracked ephemeral paths have drifted from what the manifest was
    built against, or if anything outside the plan ends up staged -
    section 11.4's explicit safety requirements."""
    repo_root = repo_root or Path.cwd()
    planned = set(manifest.all_paths)

    current: set[str] = set()
    for group_id, git_prefix, *_rest in _GROUP_DEFINITIONS:
        current.update(_group_paths(repo_root, group_id, git_prefix))
    if current != planned:
        missing = planned - current
        extra = current - planned
        raise CleanupManifestError(
            "Tracked ephemeral paths have drifted since the manifest was built - "
            f"refusing to proceed. missing={len(missing)} extra={len(extra)}"
        )

    if dry_run:
        return CleanupExecutionResult(
            dry_run=True, removed_paths=tuple(sorted(planned)), index_diff_matches_plan=True
        )

    before_status = subprocess.run(
        ["git", "diff", "--cached", "--name-status"],
        cwd=repo_root,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    if before_status.strip():
        raise CleanupManifestError(
            "Refusing to run git rm --cached against an already-dirty index "
            "(git diff --cached --name-status is non-empty) - resolve this first."
        )

    for batch in _batched(sorted(planned)):
        if not batch:
            continue
        subprocess.run(
            ["git", "rm", "--cached", "--quiet", "--", *batch],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=True,
        )

    for path in planned:
        if not (repo_root / path).is_file():
            raise CleanupManifestError(
                f"'{path}' was removed from disk by git rm --cached - this must never "
                "happen (--cached was not effective); aborting."
            )

    after_status = subprocess.run(
        ["git", "diff", "--cached", "--name-status"],
        cwd=repo_root,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    staged_paths = set()
    for line in after_status.splitlines():
        _status, _tab, path = line.partition("\t")
        staged_paths.add(path.strip())
    if staged_paths != planned:
        raise CleanupManifestError(
            "git diff --cached --name-status does not exactly match the planned "
            f"removals - refusing to leave this unverified. unexpected={staged_paths - planned!r} "
            f"missing={planned - staged_paths!r}"
        )

    return CleanupExecutionResult(
        dry_run=False, removed_paths=tuple(sorted(planned)), index_diff_matches_plan=True
    )
